#!/usr/bin/env python3
"""Build (or --check) the WoW Forever TOCs from WarbandNexus.toc.

One zip, one CurseForge / Wago project, one TOC per game type (the Details! / Questie layout):

  WarbandNexus.toc           retail (## Interface: 120105) -- the source of truth, edited by hand
  WarbandNexus_Forever.toc   WoW Forever (## Interface: 16001) -- GENERATED by this script
  WarbandNexus_Camelot.toc   the same file under Forever's other game-type suffix -- GENERATED

The Forever client picks _Forever.toc / _Camelot.toc over the plain one (warcraft.wiki.gg
TOC_format; "the Camelot value may be changed to Forever in the future", so both ship).

The Forever TOC is the retail TOC minus RETAIL_ONLY below: files for systems Forever does not
have (Great Vault, Mythic+, PvE tab, Midnight quest / world-quest catalogs, Professions tab,
Warband Bank gold tools, Weekly Progress). Every file left in loads without them -- the callers
guard each entry point (PvECacheService, PlansManager, PlansUI, UI_TabHost, ...). Adding a new
file to WarbandNexus.toc puts it in both builds; list it here if it is retail-only.

Usage:
  python scripts/build_flavor_tocs.py           write the Forever TOCs
  python scripts/build_flavor_tocs.py --check   fail if they are stale (CI / preflight)
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RETAIL_TOC = ROOT / "WarbandNexus.toc"
FOREVER_TOCS = (ROOT / "WarbandNexus_Forever.toc", ROOT / "WarbandNexus_Camelot.toc")
FOREVER_INTERFACE = "16001"

# Retail-only files: never loaded on WoW Forever. Paths as written in WarbandNexus.toc.
RETAIL_ONLY = (
    # Great Vault + Mythic+ data (PvECacheService guards every call into them)
    r"Modules\PvECacheService_MythicPlus.lua",
    r"Modules\PvECacheService_Vault.lua",
    r"Modules\PvECacheService_VaultSelfTest.lua",
    r"Modules\VaultScanner.lua",
    r"Modules\VaultButton_TrackerUI.lua",
    r"Modules\PlansManager_Vault.lua",
    # Midnight weekly quests / world quests / content events
    r"Modules\PlansManager_Quests.lua",
    r"Modules\Data\MidnightQuestCatalog.lua",
    r"Modules\DailyQuestManager_Tracking.lua",
    r"Modules\DailyQuestManager.lua",
    r"Modules\Data\ReminderWorldQuestIndex.lua",
    r"Modules\Data\ReminderMidnightFactionEmissaryData.lua",
    r"Modules\Data\ReminderMidnightWorldQuestData.lua",
    r"Modules\Data\ReminderWorldQuestCatalog.lua",
    r"Modules\UI\PlansUI_WeeklyPlanner.lua",
    r"Modules\UI\PlansUI_WeeklyProgress.lua",
    # Professions tab (Dragonflight-style knowledge / concentration model)
    r"Modules\UI\ProfessionInfoWindow.lua",
    r"Modules\UI\ProfessionsUI.lua",
    r"Modules\UI\ProfessionsUI_DrawTab.lua",
    # PvE tab body (PvEUI.lua stays: the PvP tab borrows its section shell)
    r"Modules\UI\PvEUI_CharList.lua",
    r"Modules\UI\PvEUI_BodyPaint.lua",
    r"Modules\UI\PvEUI_ColumnPicker.lua",
    # Warband Bank gold tools
    r"Modules\UI\GoldManagementPopup.lua",
    r"Modules\UI\WarbandBankDepositPopup.lua",
    r"Modules\UI\CharacterBankMoneyLogPopup.lua",
    r"Modules\GoldManagementService.lua",
    r"Modules\WarbandBankDepositService.lua",
    r"Modules\CharacterBankMoneyLogService.lua",
)

HEADER = (
    "# GENERATED by scripts/build_flavor_tocs.py from WarbandNexus.toc -- do not edit by hand.\n"
    "# WoW Forever build: WarbandNexus.toc minus the retail-only files listed in that script.\n"
)


def build_forever_toc(retail_text: str) -> str:
    lines = retail_text.splitlines()
    present = {ln.strip() for ln in lines}
    missing = [f for f in RETAIL_ONLY if f not in present]
    if missing:
        raise SystemExit("RETAIL_ONLY lists files not in WarbandNexus.toc: " + ", ".join(missing))
    excluded = set(RETAIL_ONLY)
    out = []
    for ln in lines:
        if ln.strip() in excluded:
            continue
        if re.match(r"^## Interface:", ln):
            ln = "## Interface: " + FOREVER_INTERFACE
        out.append(ln)
    return HEADER + "\n".join(out) + "\n"


def main() -> int:
    check = "--check" in sys.argv[1:]
    retail_text = RETAIL_TOC.read_text(encoding="utf-8-sig")
    m = re.search(r"(?m)^## Interface:\s*(.+)$", retail_text)
    if not m or FOREVER_INTERFACE in m.group(1):
        print(f"WarbandNexus.toc must be retail-only (## Interface without {FOREVER_INTERFACE}).",
              file=sys.stderr)
        return 1
    expected = build_forever_toc(retail_text)
    stale = []
    for path in FOREVER_TOCS:
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != expected:
            if check:
                stale.append(path.name)
            else:
                path.write_text(expected, encoding="utf-8", newline="\n")
                print(f"wrote {path.name}")
    if stale:
        print("Forever TOCs are stale (run python scripts/build_flavor_tocs.py): "
              + ", ".join(stale), file=sys.stderr)
        return 1
    if check:
        kept = sum(1 for ln in expected.splitlines()
                   if ln.strip().lower().endswith(".lua") and not ln.lstrip().startswith("#"))
        print(f"Flavor TOCs OK - Forever loads {kept} Lua files, {len(RETAIL_ONLY)} retail-only left out.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
